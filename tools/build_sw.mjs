// Writes app/sw.js: precaches the app shell; voice clips are cached as they are first
// played and then fetched in the background so the whole game works offline.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';

const APP = new URL('../app/', import.meta.url).pathname.replace(/^\/(\w:)/, '$1');
const walk = d => readdirSync(d).flatMap(f => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = walk(APP).map(p => relative(APP, p).split(sep).join('/')).filter(f => f !== 'sw.js');
const shell = files.filter(f => !f.startsWith('audio/'));
const audio = files.filter(f => f.startsWith('audio/'));
const hash = createHash('sha1');
files.sort().forEach(f => { hash.update(f); hash.update(readFileSync(join(APP, f))); });
const version = hash.digest('hex').slice(0, 10);

writeFileSync(join(APP, 'sw.js'), `// Generated by tools/build_sw.mjs
const VERSION = '${version}';
const SHELL = ${JSON.stringify(['./', ...shell])};
const AUDIO = ${JSON.stringify(audio)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open('ww-shell-' + VERSION).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (!k.endsWith(VERSION)) await caches.delete(k);
    await self.clients.claim();
    // Fill the audio cache in the background for offline play.
    const c = await caches.open('ww-audio-' + VERSION);
    for (let i = 0; i < AUDIO.length; i += 20) {
      await Promise.all(AUDIO.slice(i, i + 20).map(async u => { if (!(await c.match(u))) { try { await c.add(u); } catch (e) {} } }));
    }
  })());
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith((async () => {
    const hit = await caches.match(e.request, { ignoreSearch: true });
    if (hit) return hit;
    const res = await fetch(e.request);
    if (res.ok && new URL(e.request.url).pathname.includes('/audio/')) {
      const c = await caches.open('ww-audio-' + VERSION);
      c.put(e.request, res.clone());
    }
    return res;
  })());
});
`);
console.log('sw.js version', version, 'shell', shell.length, 'audio', audio.length);
